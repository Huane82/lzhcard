    document.querySelectorAll('[data-i18n-label]').forEach(elem => {
        const key = elem.getAttribute('data-i18n-label');
        if (dict[key]) {
            elem.setAttribute('label', dict[key]);
        } else if (I18N_DICTIONARY['zh-TW'][key]) {
            elem.setAttribute('label', I18N_DICTIONARY['zh-TW'][key]);
        }
    });

    if (typeof updateCategorySelects === 'function') {
        updateCategorySelects();
    }

